// Embeds the lookup tables and affixes of web/tables.mjs into models/relay/host/tables_data.h as one JSON string (key order kept:
// table indices follow it).   node models/relay/host/gen_tables.mjs > models/relay/host/tables_data.h
import {TABLES, AFFIXES} from '../web/tables.mjs';

const json = JSON.stringify({tables: TABLES, affixes: AFFIXES});
const lines = [];
for (let i = 0; i < json.length; i += 100) lines.push(JSON.stringify(json.slice(i, i + 100)));
process.stdout.write('/* Generated by models/relay/host/gen_tables.mjs from web/tables.mjs. Do not edit. */\n' +
  'static const char RELAY_TABLES_JSON[] =\n    ' + lines.join('\n    ') + ';\n');
