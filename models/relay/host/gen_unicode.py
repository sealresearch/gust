"""Generates unicode_data.h for the native Relay host (Python's unicodedata, Unicode 16.0):
    python models/relay/host/gen_unicode.py > models/relay/host/unicode_data.h
Tables (all sorted, looked up by binary search):
  uc_cat_ranges   [start, end, flags]: UC_L letter, UC_N number, UC_Z separator, UC_M mark, UC_ND decimal digit,
                  UC_C other (general category)
  uc_ccc_tab      [cp, ccc] canonical combining class (nonzero only)
  uc_decomp       [cp, offset, len] full canonical decomposition (NFD of the code point; Hangul syllables excluded,
                  done algorithmically) into uc_decomp_pool
  uc_comp         [first, second, composite] canonical compositions (primary composites, exclusions removed)
  uc_lower/upper  [cp, offset, len] full case mappings (str.lower / str.upper of one character) into uc_case_pool
  uc_fold         [cp, folded] simple case folding (case-insensitive regexes)
"""
import sys
import unicodedata as ud

MAXCP = 0x110000


def cat_flags(cp):
    c = ud.category(chr(cp))
    f = {"L": 1, "N": 2, "Z": 4, "M": 8, "C": 32}.get(c[0], 0)
    if c == "Nd":
        f |= 16
    return f


def emit(out, name, rows, fmt):
    out.write("static const uint32_t %s[][%d] = {\n" % (name, len(rows[0]) if rows else 1))
    for r in rows:
        out.write("    {" + ", ".join(fmt % x for x in r) + "},\n")
    out.write("};\n#define %s_N %d\n\n" % (name.upper(), len(rows)))


def emit_pool(out, name, pool):
    out.write("static const uint32_t %s[] = {\n" % name)
    for i in range(0, len(pool), 12):
        out.write("    " + ", ".join("0x%x" % x for x in pool[i:i + 12]) + ",\n")
    out.write("};\n\n")


def main():
    out = sys.stdout
    out.write("/* Generated by models/relay/host/gen_unicode.py from Python unicodedata %s. Do not edit. */\n" % ud.unidata_version)
    out.write("#define UC_L 1u\n#define UC_N 2u\n#define UC_Z 4u\n#define UC_M 8u\n#define UC_ND 16u\n#define UC_C 32u\n\n")
    ranges, cur = [], None
    for cp in range(MAXCP):
        f = cat_flags(cp)
        if cur and cur[2] == f and cur[1] == cp - 1:
            cur[1] = cp
        else:
            if cur and cur[2]:
                ranges.append(tuple(cur))
            cur = [cp, cp, f]
    if cur and cur[2]:
        ranges.append(tuple(cur))
    emit(out, "uc_cat_ranges", ranges, "0x%x")
    emit(out, "uc_ccc_tab", [(cp, ud.combining(chr(cp))) for cp in range(MAXCP) if ud.combining(chr(cp))], "0x%x")
    pool, dec = [], []
    for cp in range(MAXCP):
        if 0xAC00 <= cp <= 0xD7A3:
            continue
        ch = chr(cp)
        d = ud.normalize("NFD", ch)
        if d != ch:
            dec.append((cp, len(pool), len(d)))
            pool.extend(ord(x) for x in d)
    emit_pool(out, "uc_decomp_pool", pool)
    emit(out, "uc_decomp", dec, "0x%x")
    comp = []
    for cp in range(MAXCP):
        if 0xAC00 <= cp <= 0xD7A3:
            continue
        raw = ud.decomposition(chr(cp))
        if not raw or raw.startswith("<"):
            continue
        parts = [int(x, 16) for x in raw.split()]
        if len(parts) == 2 and ud.normalize("NFC", chr(parts[0]) + chr(parts[1])) == chr(cp):
            comp.append((parts[0], parts[1], cp))
    comp.sort()
    emit(out, "uc_comp", comp, "0x%x")
    cpool = []
    for name, fn in (("uc_lower", str.lower), ("uc_upper", str.upper)):
        ent = []
        for cp in range(MAXCP):
            if 0xD800 <= cp < 0xE000:
                continue
            m = fn(chr(cp))
            if m != chr(cp):
                ent.append((cp, len(cpool), len(m)))
                cpool.extend(ord(x) for x in m)
        emit(out, name, ent, "0x%x")
    emit_pool(out, "uc_case_pool", cpool)
    fold = []
    for cp in range(MAXCP):
        if 0xD800 <= cp < 0xE000:
            continue
        ch = chr(cp)
        lo = ch.lower()
        f = lo if len(lo) == 1 else (ch.casefold() if len(ch.casefold()) == 1 else ch)
        if f != ch:
            fold.append((cp, ord(f)))
    emit(out, "uc_fold", fold, "0x%x")


if __name__ == "__main__":
    main()
