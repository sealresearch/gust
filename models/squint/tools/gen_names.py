#!/usr/bin/env python3
"""Generates host/names_<instance>.h: one #define per global symbol of a Squint host instance.

The JavaScript build ran each host in its own WebAssembly module, so two modules could hold the same code with separate
state (for example the tracker's and the acquirer's verifier host). In one native library that needs separate symbol
names. Each instance below is compiled with `-include names_<instance>.h`, which renames every global it defines.

Run from models/squint:  python tools/gen_names.py [zig]
"""
import os, struct, subprocess, sys, tempfile
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

HOST = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'host')
ZIG = sys.argv[1] if len(sys.argv) > 1 else os.environ.get('ZIG', 'zig')
from instances import INSTANCES
FLAGS = ['-std=c11', '-O1', '-ffp-contract=off', '-DSQUINT_FRAME_CAPACITY=921600', '-I' + HOST, '-target', 'x86_64-linux-gnu']


def defined_globals(path):
    """Names of the global (or weak) symbols an ELF64 little-endian object defines."""
    d = open(path, 'rb').read()
    shoff, = struct.unpack_from('<Q', d, 0x28)
    shentsize, shnum = struct.unpack_from('<HH', d, 0x3A)
    secs = [struct.unpack_from('<IIQQQQIIQQ', d, shoff + i * shentsize) for i in range(shnum)]
    names = []
    for s in secs:
        if s[1] != 2:  # SHT_SYMTAB
            continue
        strtab = secs[s[6]]
        for off in range(s[4], s[4] + s[5], 24):
            name, info, other, shndx, value, size = struct.unpack_from('<IBBHQQ', d, off)
            if (info >> 4) in (1, 2) and shndx != 0:
                end = d.index(b'\0', strtab[4] + name)
                names.append(d[strtab[4] + name:end].decode())
    return names


def main():
    for inst, files in INSTANCES.items():
        names = set()
        with tempfile.TemporaryDirectory() as tmp:
            for f in files:
                obj = os.path.join(tmp, f + '.o')
                subprocess.run([ZIG, 'cc', *FLAGS, '-c', os.path.join(HOST, f), '-o', obj], check=True)
                names.update(defined_globals(obj))
        names.discard('sq_clock_seconds')
        out = os.path.join(HOST, f'names_{inst}.h')
        with open(out, 'w', newline='\n') as h:
            h.write(f'/* Generated by tools/gen_names.py: the global symbols of the Squint "{inst}" host instance. Do not edit. */\n')
            for n in sorted(names):
                h.write(f'#define {n} sq_{inst}_{n}\n')
        print(inst, len(names))


main()
