// Generates host/squint_kernels.h: the Gaussian kernels (sigma 1, 2, 3) the tracker blurs its template with, computed
// exactly as the JavaScript release did (Float32Array of Math.exp, normalized by a double sum), so the C port does not
// depend on any C library's exp. Run: node tools/gen_kernels.mjs
import {writeFileSync} from 'node:fs';
const out = ['/* Generated by tools/gen_kernels.mjs. Do not edit. Float32 kernels of the template blur, sigma 1, 2 and 3. */'];
const hex = x => {
  const b = Buffer.alloc(4);
  b.writeFloatBE(x);
  return '0x' + b.toString('hex');
};
for (const sigma of [1, 2, 3]) {
  const radius = Math.ceil(3 * sigma);
  const k = Float32Array.from({length: radius * 2 + 1}, (_, i) => Math.exp(-((i - radius) ** 2) / (2 * sigma * sigma)));
  const sum = k.reduce((a, b) => a + b);
  for (let i = 0; i < k.length; i++) k[i] /= sum;
  out.push(`#define SQ_KERNEL${sigma}_RADIUS ${radius}`);
  out.push(`static const uint32_t sq_kernel${sigma}_bits[${k.length}] = {${Array.from(k, hex).join(', ')}};`);
}
writeFileSync(new URL('../host/squint_kernels.h', import.meta.url), out.join('\n') + '\n');
