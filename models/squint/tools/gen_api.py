#!/usr/bin/env python3
"""Generates host/squint_api.h: the prototypes of every exported (API) function of the Squint hosts, as one macro per
instance group. SQUINT_API_<GROUP>(prefix) declares them with the instance's symbol prefix, so squint.c can call a
host through its renamed symbols with the signature the host defines. Run from models/squint: python tools/gen_api.py"""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from instances import API_GROUPS

HOST = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'host')
DEF = re.compile(r'^API\s+([A-Za-z_][\w \*]*?)\s*(\w+)\(([^)]*)\)\s*\{', re.M)

with open(os.path.join(HOST, 'squint_api.h'), 'w', newline='\n') as out:
    out.write('/* Generated by tools/gen_api.py from the API functions of the host sources. Do not edit. */\n#ifndef SQUINT_API_H\n#define SQUINT_API_H\n#include <stdint.h>\n')
    for group, files in API_GROUPS.items():
        protos = {}
        for f in files:
            text = open(os.path.join(HOST, f), encoding='utf-8').read()
            for ret, name, args in DEF.findall(text):
                args = ' '.join(args.split()) or 'void'
                protos[name] = f'{" ".join(ret.split())} P##{name}({args})'
        out.write(f'#define SQUINT_API_{group.upper()}(P) ')
        out.write(' '.join(f'extern {p};' for _, p in sorted(protos.items())))
        out.write('\n')
        print(group, len(protos))
    out.write('#endif\n')
